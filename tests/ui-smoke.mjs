import { chromium } from 'playwright';
import fs from 'node:fs';
fs.mkdirSync('artifacts',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:393,height:852},deviceScaleFactor:1,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
const assert=(condition,message)=>{if(!condition)throw Error(message)};
try{
await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});
await page.evaluate(()=>localStorage.clear());await page.reload({waitUntil:'networkidle'});
await page.locator('[data-go="game"]').first().click();
assert(await page.locator('#board .cell').count()===64,'8x8 board missing');
assert(await page.locator('#tray .piece').count()===3,'Three pieces missing');
await page.screenshot({path:'artifacts/01-puzzle.png',fullPage:true});
await page.locator('#tray .piece').first().click();
const cells=page.locator('#board .cell');let placed=false;
for(let i=0;i<64;i++){await cells.nth(i).click();if(Number(await page.locator('#score').innerText())>0){placed=true;break}}
assert(placed,'Tap placement failed');
const saved=await page.locator('#score').innerText();
await page.reload({waitUntil:'networkidle'});
await page.locator('[data-go="game"]').first().click();
assert(await page.locator('#score').innerText()===saved,'Score not persisted');
await page.locator('#game [data-go="room"]').click();
assert(await page.locator('#room').innerText().then(s=>s.includes('Pamuk')),'Room missing');
const coinsBefore=Number((await page.locator('.coins').first().innerText()).replace(/[^0-9]/g,''));
await page.locator('#feed').click();
assert(Number((await page.locator('.coins').first().innerText()).replace(/[^0-9]/g,''))===coinsBefore-25,'Feeding deduction failed');
await page.locator('#room [data-buy="lamp"]').click();
assert((await page.locator('#roomdecor').innerText()).includes('💡'),'Room purchase not reflected');
await page.screenshot({path:'artifacts/02-room.png',fullPage:true});
await page.locator('#room [data-go="game"]').click();
await page.locator('#game [data-go="garden"]').click();
await page.locator('#garden [data-buy="rose"]').click();
assert((await page.locator('#gardenplants').innerText()).includes('🌹'),'Garden purchase not reflected');
await page.screenshot({path:'artifacts/03-garden.png',fullPage:true});
await page.reload({waitUntil:'networkidle'});
await page.locator('[data-go="game"]').first().click();
await page.locator('#game [data-go="room"]').click();
assert((await page.locator('#roomdecor').innerText()).includes('💡'),'Room purchase not saved');
await page.locator('#room [data-go="game"]').click();
page.once('dialog',dialog=>dialog.accept());
await page.locator('#restart').click();
assert(await page.locator('#score').innerText()==='0','Restart failed');
assert(errors.length===0,'Browser errors: '+errors.join('; '));
console.log('Cat Haven UI smoke tests passed');
}finally{await browser.close()}
