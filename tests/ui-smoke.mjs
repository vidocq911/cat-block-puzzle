import { chromium } from 'playwright';
import fs from 'node:fs';
fs.mkdirSync('artifacts',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:393,height:852},deviceScaleFactor:1,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
const assert=(condition,message)=>{if(!condition)throw Error(message)};
try{
await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});
await page.evaluate(()=>localStorage.clear());await page.reload({waitUntil:'networkidle'});
assert(await page.locator('#board .cell').count()===64,'8x8 board missing');
assert(await page.locator('#tray .piece').count()===3,'Three pieces missing');
await page.screenshot({path:'artifacts/01-puzzle.png',fullPage:true});
await page.locator('#tray .piece').first().click();
await page.locator('#board .cell').first().click();
assert(Number(await page.locator('#score').innerText())>0,'Tap placement failed');
const saved=await page.locator('#score').innerText();
await page.reload({waitUntil:'networkidle'});
assert(await page.locator('#score').innerText()===saved,'Score not persisted');
await page.locator('[data-tab="cats"]').click();
assert(await page.locator('#panel').innerText().then(s=>s.includes('Pamuk')),'Cat panel missing');
const beforeFeed=Number(await page.locator('#coins').innerText());
await page.locator('[data-care="feed"]').click();
assert(Number(await page.locator('#coins').innerText())===beforeFeed-25,'Feeding coin deduction incorrect');
await page.screenshot({path:'artifacts/02-cat.png',fullPage:true});
await page.locator('[data-tab="room"]').click();
await page.locator('[data-buy="lamp"]').click();
assert(await page.locator('#decor').innerText()==='💡','Room purchase not reflected');
await page.locator('[data-tab="garden"]').click();
await page.locator('[data-buy="flower"]').click();
assert((await page.locator('#panel').innerText()).includes('🌼'),'Garden purchase not reflected');
await page.screenshot({path:'artifacts/03-garden.png',fullPage:true});
await page.reload({waitUntil:'networkidle'});
assert((await page.locator('#decor').innerText()).includes('💡'),'Room purchase not saved');
await page.locator('#restart').click();
assert(await page.locator('#score').innerText()==='0','Restart failed');
assert(errors.length===0,'Browser errors: '+errors.join('; '));
console.log('Cat Haven smoke tests passed');
}finally{await browser.close()}
